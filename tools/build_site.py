#!/usr/bin/env python3
"""Build the app's data (data/) from sources/manifest.json and the parsed releases in sources/parsed/.

  data/releases.js     every release (dates, versions, document links, counts); loaded on start
  data/changes.js      for every R code: its names over time, and what changed in each release; loaded on start
  data/v/<id>.js       one release in full (criteria, tests, pathway …); loaded when needed

Releases are ordered by the date they came into force ('inForceFrom', else 'published'). A change is recorded against
the release where it first appears. Text is compared after normalising spaces, dashes and quotes, so a change only in
layout is not reported (the side-by-side view in the app still shows every character).

Usage: python3 tools/build_site.py"""
import datetime, json, os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
SRC = os.path.join(ROOT, 'sources')
OUT = os.path.join(ROOT, 'data')
TEST_FIELDS = [('target', 'target'), ('method', 'method'), ('commissioning', 'commissioning'),
               ('family', 'family structure'), ('scope', 'scope')]


def norm(s):
    s = str(s or '')
    s = re.sub(r'[‐-―−]', '-', s)
    s = re.sub(r'[‘’‛`]', "'", s)
    s = re.sub(r'[“”]', '"', s)
    s = re.sub(r'\s*-\s*', '-', s)
    return re.sub(r'\s+', ' ', s).strip().lower()


def crit_text(e):
    # spacing is ignored: PDF text extraction can split or run words together, and a change only in spaces is never a
    # change in wording
    return re.sub(r'\s+', '', norm(' '.join(f'{m} {t}' for _, m, t in e.get('criteria', []))))


def words(s):
    return set(re.findall(r'[a-z0-9]+', norm(s))) - {'and', 'or', 'the', 'of', 'with', 'for', 'in', 'a', 'to', 'disease', 'disorders', 'disorder'}


def release_date(r):
    return r.get('inForceFrom') or r['published']


def diff_tests(a, b):
    """Plain-language details of how the tests of one indication changed."""
    out = []
    ta, tb = {t['id']: t for t in a.get('tests', [])}, {t['id']: t for t in b.get('tests', [])}
    for tid in sorted(set(ta) | set(tb), key=lambda x: [int(p) for p in re.findall(r'\d+', x)]):
        if tid not in ta:
            t = tb[tid]; out.append(f'{tid} added: {t.get("target", "")} ({t.get("method", "")})'.replace(' ()', ''))
        elif tid not in tb:
            t = ta[tid]; out.append(f'{tid} removed: {t.get("target", "")} ({t.get("method", "")})'.replace(' ()', ''))
        else:
            for key, label in TEST_FIELDS:
                x, y = ta[tid].get(key, ''), tb[tid].get(key, '')
                # a field only one release has (a column added later, or family/scope from a PDF not loaded) is not a change
                if x and y and norm(x) != norm(y): out.append(f'{tid} {label}: {x} → {y}')
    return out


def compare(a, b):
    """(kinds, details) for one code between two consecutive releases; a or b may be None."""
    if a is None: return ['added'], []
    if b is None: return ['removed'], []
    kinds, det = [], []
    if norm(a['name']) != norm(b['name']): kinds.append('name'); det.append(f'Renamed from “{a["name"]}” to “{b["name"]}”')
    td = diff_tests(a, b)
    if td: kinds.append('tests'); det += td
    pa = sorted({p for t in a.get('tests', []) for p in t.get('panels', [])})
    pb = sorted({p for t in b.get('tests', []) for p in t.get('panels', [])})
    if pa != pb: kinds.append('panels')
    for key, label in (('overlapping', 'overlapping'), ('pathway', 'pathway'), ('specialties', 'specialties')):
        x, y = a.get(key), b.get(key)
        if x is not None and y is not None and norm(json.dumps(x, ensure_ascii=False)) != norm(json.dumps(y, ensure_ascii=False)):
            kinds.append(label)
    return kinds, det


def suggest_links(prev, cur, rid):
    """Codes that disappear in a release, with the codes that seem to replace them (named in the new text, or similar name)."""
    gone = [c for c in prev if c not in cur]
    new = [c for c in cur if c not in prev]
    out = []
    for g in gone:
        cands = []
        for c, e in cur.items():
            blob = ' '.join([e.get('change', '')] + e.get('overlapping', []) + [t for _, _, t in e.get('criteria', [])])
            if re.search(rf'\b{g}\b', blob): cands.append((c, f'{c} mentions {g}'))
        gw = words(prev[g]['name'])
        for c in new:
            cw = words(cur[c]['name'])
            if gw and cw and len(gw & cw) / len(gw | cw) >= 0.5 and c not in [x for x, _ in cands]:
                cands.append((c, f'similar name: {cur[c]["name"]}'))
        out.append({'from': g, 'release': rid, 'to': [c for c, _ in cands], 'why': [w for _, w in cands], 'auto': True})
    return out


def write_js(path, comment, expr):
    with open(path, 'w', encoding='utf-8') as f:
        f.write(f'/* {comment} Generated by tools/build_site.py; do not edit by hand. */\n{expr};\n')


def dump(o):
    return json.dumps(o, ensure_ascii=False, separators=(',', ':'))


def main():
    manifest = json.load(open(os.path.join(SRC, 'manifest.json'), encoding='utf-8'))
    rels = [r for r in manifest['releases'] if os.path.exists(os.path.join(SRC, 'parsed', r['id'] + '.json'))]
    skipped = [r['id'] for r in manifest['releases'] if r not in rels]
    rels.sort(key=release_date)
    if not rels: sys.exit('No parsed releases: run tools/parse_version.py first.')
    curated = []
    if os.path.exists(os.path.join(SRC, 'code-links.json')):
        curated = json.load(open(os.path.join(SRC, 'code-links.json'), encoding='utf-8')).get('links', [])

    os.makedirs(os.path.join(OUT, 'v'), exist_ok=True)
    codes, prev, links, summary = {}, None, [], []
    # Criteria come from the PDF, which not every release has: compare each code's criteria with the last release that had
    # them, and say so when releases without criteria lie in between (the change was published somewhere in that span).
    last_crit, prev_id = {}, None
    for r in rels:
        p = json.load(open(os.path.join(SRC, 'parsed', r['id'] + '.json'), encoding='utf-8'))
        cur = {e['code']: e for e in p['indications']}
        write_js(os.path.join(OUT, 'v', r['id'] + '.js'), f'Release {r["label"]} of the rare and inherited disease test directory, verbatim.',
                 f'TDH.addRelease({dump(r["id"])},{dump({"changeLog": p.get("changeLog", []), "indications": p["indications"]})})')
        changed = 0
        has_crit = any(e.get('criteria') for e in p['indications'])
        for c in sorted(set(cur) | set(prev or {}), key=lambda c: int(c[1:])):
            a = prev.get(c) if prev is not None else None
            b = cur.get(c)
            rec = codes.setdefault(c, {'names': [], 'events': [], 'present': []})
            if b:
                rec['present'].append(r['id'])
                if not rec['names'] or norm(rec['names'][-1][1]) != norm(b['name']): rec['names'].append([r['id'], b['name']])
            crit_ev = None
            if has_crit and b and b.get('criteria'):
                t = crit_text(b)
                if c in last_crit and last_crit[c][1] != t:
                    crit_ev = None if last_crit[c][0] == prev_id else f'Eligibility criteria compared with {last_crit[c][2]}, the most recent earlier version with its criteria loaded: the change was published between the two'
                    crit_ev = crit_ev or True
                last_crit[c] = (r['id'], t, r['label'])
            if prev is None:  # the first release is the baseline: nothing to compare with, but keep the spreadsheet's own change note
                if b.get('change'): rec['events'].append({'r': r['id'], 'k': ['noted'], 'n': b['change']})
                continue
            if a is None and b is None: continue
            kinds, det = compare(a, b)
            if crit_ev:
                kinds.insert(1 if 'name' in kinds else 0, 'criteria')
                if crit_ev is not True: det.insert(0, crit_ev)
            # a note carried over unchanged from the previous release (same spreadsheet) is not news
            note = (b or {}).get('change', '') if (b or {}).get('change', '') != (a or {}).get('change', '') else ''
            if kinds or note:
                ev = {'r': r['id'], 'k': kinds}
                if det: ev['d'] = det
                if note: ev['n'] = note
                rec['events'].append(ev); changed += 1
        if prev is not None: links += suggest_links(prev, cur, r['id'])
        summary.append(f'{r["id"]} ({release_date(r)}): {len(cur)} codes' + (f', {changed} with changes' if prev is not None else ' (baseline)'))
        r_out = {k: r[k] for k in ('id', 'label', 'published', 'datePrecision', 'inForceFrom', 'directory', 'criteria', 'links', 'parsedFrom') if r.get(k)}
        r_out['counts'] = {'indications': len(cur), 'tests': sum(len(e['tests']) for e in cur.values())}
        if p.get('problems'): r_out['problems'] = len(p['problems'])
        if not has_crit: r_out['noCriteria'] = True
        r['_out'] = r_out
        prev, prev_id = cur, r['id']

    # gene index for search: which R codes in the latest release test each gene (named in the target, or a green gene on
    # the test's PanelApp panel at its latest sign-off)
    genes = {}
    def panel_now(pid):
        f = os.path.join(OUT, 'panels', f'{pid}.js')
        if not os.path.exists(f): return set()
        d = json.loads(re.search(r'TDH\.addPanel\(\d+,(.*)\);', open(f, encoding='utf-8').read(), re.S).group(1))
        g = set()
        for so in d['signoffs']: g |= set(so['add']); g -= set(so['rem'])
        return {x for x in g if '(' not in x}
    for e in prev.values():
        found = set()
        for t in e['tests']:
            found |= {w for w in re.findall(r'\b[A-Z][A-Z0-9]{1,9}(?:-[A-Z0-9]+)?\b', t.get('target', '')) if re.search(r'\d', w) or len(w) >= 3}
            for pid in t.get('panels', []): found |= panel_now(pid)
        for gname in found - {'WGS', 'WES', 'MLPA', 'STR', 'CNV', 'DNA', 'FISH', 'NIPD', 'NHS', 'GLH', 'HBS'}:
            genes.setdefault(gname, []).append(e['code'])
    write_js(os.path.join(OUT, 'genes.js'), 'Genes tested by each R code in the latest release (search index).',
             f'TDH.addGenes({dump(dict(sorted(genes.items())))})')
    # panel index (for the Gene changes view): every panel with a saved history, its sign-off span, and the R codes whose
    # tests use it now (c) or used it in an earlier release (o); and which panels each gene has ever been on (any rating)
    uses_now, uses_ever = {}, {}
    for r in rels:
        pr = json.load(open(os.path.join(SRC, 'parsed', r['id'] + '.json'), encoding='utf-8'))
        for e in pr['indications']:
            for t in e['tests']:
                for pid in t.get('panels', []):
                    uses_ever.setdefault(pid, set()).add(e['code'])
                    if r is rels[-1]: uses_now.setdefault(pid, set()).add(e['code'])
    pindex, gpanels = {}, {}
    pdir = os.path.join(OUT, 'panels')
    for f in sorted(os.listdir(pdir) if os.path.isdir(pdir) else []):
        if not f.endswith('.js'): continue
        pid = int(f[:-3])
        d = json.loads(re.search(r'TDH\.addPanel\(\d+,(.*)\);', open(os.path.join(pdir, f), encoding='utf-8').read(), re.S).group(1))
        if not d['signoffs']: continue
        key = lambda c: int(c[1:])
        now_ = sorted(uses_now.get(pid, ()), key=key)
        pindex[pid] = {'n': d['name'], 'f': d['signoffs'][0]['date'], 'l': d['signoffs'][-1]['date'], 'c': now_,
                       'o': sorted(uses_ever.get(pid, set()) - set(now_), key=key)}
        for so in d['signoffs']:
            for k in ('add', 'aa', 'ra'):
                for g in so.get(k, []): gpanels.setdefault(g, set()).add(pid)
    write_js(os.path.join(OUT, 'panel-index.js'), 'PanelApp panels with a signed-off history: name, first and last sign-off, R codes using them.',
             f'TDH.addPanelIndex({dump(pindex)})')
    write_js(os.path.join(OUT, 'gene-panels.js'), 'Panels each gene has been on at any GMS sign-off (any rating).',
             f'TDH.addGenePanels({dump({g: sorted(v) for g, v in sorted(gpanels.items())})})')
    # curated links win over automatic suggestions for the same code
    cur_from = {(l['from'], l.get('release')) for l in curated}
    links = curated + [l for l in links if (l['from'], l['release']) not in cur_from]
    today = datetime.date.today().isoformat()
    write_js(os.path.join(OUT, 'releases.js'), 'Releases of the rare and inherited disease test directory, oldest first.',
             f'const TDH_RELEASES = {dump([r["_out"] for r in rels])};\nconst TDH_BUILT = {dump(today)}')
    write_js(os.path.join(OUT, 'changes.js'), 'What changed for each R code in each release.',
             f'const TDH_CHANGES = {dump(codes)};\nconst TDH_LINKS = {dump(links)}')
    for s in summary: print(s)
    if skipped: print('Not built (no parsed file yet):', ', '.join(skipped))
    for l in links:
        if l.get('auto'): print(f'  check link: {l["from"]} gone in {l["release"]} → {", ".join(l["to"]) or "no replacement found"}')


if __name__ == '__main__':
    main()
