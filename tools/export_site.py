#!/usr/bin/env python3
"""Copy the app into another static site, e.g. GeneRoute's test-directory-changes/ folder (generoute.co.uk).

Copies index.html, style.css, js/ and data/ (not sources/: the original spreadsheets and PDFs stay in this repository,
and the copied page links to them on this repository's GitHub Pages site). Adjusts the page for a site where it sits
one folder down beside the Test Directory Explorer, and adds ?v= tags so browsers load changed files.

Usage: python3 tools/export_site.py <destination folder>   e.g. ../generoute/test-directory-changes"""
import datetime, os, re, shutil, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
DOCS = 'https://cjs1218.github.io/Genomic-Test-Directory-Changes/'


def main():
    if len(sys.argv) != 2: sys.exit(__doc__)
    dest = os.path.abspath(sys.argv[1])
    if os.path.exists(dest):
        for name in ('data', 'js'):
            shutil.rmtree(os.path.join(dest, name), ignore_errors=True)
    os.makedirs(dest, exist_ok=True)
    shutil.copytree(os.path.join(ROOT, 'data'), os.path.join(dest, 'data'))
    shutil.copytree(os.path.join(ROOT, 'js'), os.path.join(dest, 'js'))
    shutil.copy(os.path.join(ROOT, 'style.css'), dest)
    os.makedirs(os.path.join(dest, 'assets'), exist_ok=True)
    for f in ('changes-icon.png', 'favicon-48.png', 'apple-touch-icon.png'):
        shutil.copy(os.path.join(ROOT, 'assets', f), os.path.join(dest, 'assets', f))
    old_icon = os.path.join(dest, 'changes-icon.svg')
    if os.path.exists(old_icon): os.remove(old_icon)
    v = datetime.date.today().strftime('%Y%m%d')
    html = open(os.path.join(ROOT, 'index.html'), encoding='utf-8').read()
    html = html.replace('href="https://generoute.co.uk/"', 'href="../"')
    html = html.replace('href="https://generoute.co.uk/test-directory-explorer/"', 'href="../test-directory-explorer/"')
    html = html.replace('<link rel="stylesheet" href="style.css">', f'<link rel="stylesheet" href="style.css?v={v}">')
    html = re.sub(r'<script src="((?:js|data)/[\w.-]+\.js)"></script>', lambda m: f'<script src="{m.group(1)}?v={v}"></script>', html)
    html = html.replace('<script src="js/core.js', f'<script>window.TDH_DOCS_BASE = {DOCS!r};</script>\n  <script src="js/core.js', 1)
    open(os.path.join(dest, 'index.html'), 'w', encoding='utf-8').write(html)
    with open(os.path.join(dest, 'README.md'), 'w') as f:
        f.write('# Test Directory Changes (copy)\n\nGenerated by tools/export_site.py in '
                '[cjs1218/Genomic-Test-Directory-Changes](https://github.com/cjs1218/Genomic-Test-Directory-Changes); '
                'do not edit here. Make changes there and export again.\n')
    print(f'Exported to {dest} (?v={v})')


if __name__ == '__main__':
    main()
